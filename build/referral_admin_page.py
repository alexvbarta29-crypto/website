def referral_admin_page(depth=1, seo_title=None):
    """Full HTML for admin/referrals.html: key screen, dashboard, the two
    templates the script clones, the toast and the confirm dialog. Uses
    C.head for the shared <head> (fonts, styles.css, noindex) but not
    C.nav/C.page_end: this is an app screen, not a marketing page."""
    seo_title = seo_title or (lambda s: s)
    root = C.rel(depth)
    # C.ASSET_VER is stamped by the build just before pages render, so it is
    # read here per call and never captured at import time.
    css = f'<link rel="stylesheet" href="{root}assets/css/referral-admin.min.css?v={C.ASSET_VER}">\n'
    js = f'<script src="{root}assets/js/referral-admin.min.js?v={C.ASSET_VER}" defer></script>'
    html = C.head(
        title=seo_title("Referral Dashboard"),
        desc="Office dashboard for the customer referral program.",
        slug="admin/referrals.html", depth=depth, schema=None, noindex=True, extra_head=css,
        analytics=False)
    # The offer and contact details ride on <main> as data attributes
    # (sitedata via this module), so the script's text-message templates and
    # reward labels print the same numbers as the pages without owning any.
    main_attrs = (f'data-api="{API}" data-friend-off="{FRIEND_OFF}" data-credit="{CREDIT}" '
                  f'data-gift="{GIFT}" data-prefix="{PREFIX}" data-biz="{C._esc(BIZ["name"])}" '
                  f'data-phone="{BIZ["phone_display"]}"')
    html += f"""{_header(root)}
<main id="main" class="ra-main" {main_attrs}>
  {_key_screen()}
  {_dashboard()}
  <div class="ra-toast" id="ra-toast" role="status" aria-live="polite"></div>
  {_dialog()}
  {_card_template()}
  {_referrer_template()}
</main>
{js}
</body>
</html>"""
    return html
