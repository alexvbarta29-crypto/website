def _icon(name):
    if name in _EXTRA_ICONS:
        return f"<svg {_ATTRS}>{_EXTRA_ICONS[name]}</svg>"
    return icon(name)


def _status_options():
    return "".join(f'<option value="{v}">{label}</option>' for v, label in STATUSES)


