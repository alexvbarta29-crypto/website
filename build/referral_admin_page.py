"""Office-facing referral dashboard page.

Generated by build.py (see docs/REFERRAL-PROGRAM.md, "Admin dashboard"):

  referral_admin_page(depth) -> admin/referrals.html   noindex, key-protected

App-like page: no site nav/footer, its own compact header. Styling in
assets/css/referral-admin.css, behaviour in assets/js/referral-admin.js
(minified/cache-busted by the build like the other assets).
"""
import components as C
from icons import icon
from sitedata import BIZ, REFERRAL

